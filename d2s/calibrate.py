"""Calibration: replaces the hand-measured first-line table. Generates a calibration deck (a normal Claude-style deck, one slide per
font, rows = weights, columns = CSS line heights) that goes through the same extract + build + Google round trip as any deck. `fit`
then compares Google's rendering with the browser's and writes calibration.json:
  fonts[family].dy      [[css line-height, first-line offset as a fraction of font size], ...]   (Google minus browser, px/px)
  fonts[family].natural line-height/em as Google behaves, only written when it differs >1% from the font file's hhea value
Run once per set of fonts; the file is reusable for every deck that uses those fonts."""
import json, os
import numpy as np
from .imgdiff import load, ink_bbox

LHS = [0.9, 1.0, 1.1, 1.2, 1.3, 1.4, 1.5]
FS = 60; CELL_W = 250; COL0 = 40; ROW_H = 400; ROW0 = 70; NLINES = 4

def make_deck(deck_json, fonts_used, outdir, weights=(400,)):
    """fonts_used: {family: {'weights': [...]}} (fonts.json). Writes outdir/{deck.json,deck.css,slides/*.html}."""
    src = json.load(open(deck_json)); faces = {v['family']: v for v in src['faces'].values()}
    fams = [f for f in fonts_used if f in faces]; os.makedirs(outdir + '/slides', exist_ok=True); order = []; cells = []
    for si, fam in enumerate(fams):
        sid = 'calib%d' % si; order.append(sid); html = ['<section id="%s">' % sid]
        for ri, w in enumerate(weights):
            for ci, lh in enumerate(LHS):
                x, y = COL0 + ci * CELL_W, ROW0 + ri * ROW_H
                html.append('<div style="position:absolute;left:%dpx;top:%dpx;width:%dpx;font-family:\'%s\';font-weight:%d;font-size:%dpx;line-height:%s;color:#000">%s</div>' % (x, y, CELL_W - 20, fam, w, FS, lh, '<br>'.join('EH'[i % 2] for i in range(NLINES))))
                cells.append(dict(slide=si + 1, fam=fam, w=w, lh=lh, box=[x - 12, y + 2, x + CELL_W - 12, y + ROW_H - 40]))
        html.append('</section>'); open('%s/slides/%s.html' % (outdir, sid), 'w').write('\n'.join(html))
    json.dump(dict(v=5, title='calibration', order=order, faces={k: v for k, v in src['faces'].items() if v['family'] in fams}), open(outdir + '/deck.json', 'w'))
    open(outdir + '/deck.css', 'w').write('section{background:#fff;color:#000;padding:0;display:block}')
    json.dump(cells, open(outdir + '/cells.json', 'w'), indent=1); return cells

def _line_tops(I, box):
    x0, y0, x1, y1 = box; ink = (I[y0:y1, x0:x1].max(2) < 110).any(1); runs = []; start = None
    for i, v in enumerate(ink):
        if v and start is None: start = i
        if not v and start is not None: runs.append((start + y0, i - 1 + y0)); start = None
    if start is not None: runs.append((start + y0, y1 - 1))
    return runs

def fit(calib_dir, workdir, thumbdir, table):
    """calib_dir: the generated calibration deck dir; workdir: its extract output (full_NN.png); thumbdir: Google images pN.png."""
    cells = json.load(open(calib_dir + '/cells.json')); acc = {}; imgs = {}
    for c in cells:
        n = c['slide']
        if n not in imgs: imgs[n] = (load('%s/full_%02d.png' % (workdir, n)), load('%s/p%d.png' % (thumbdir, n)))
        A, G = imgs[n]; ra, rg = _line_tops(A, c['box']), _line_tops(G, c['box'])
        if len(ra) < NLINES or len(rg) < NLINES: print('cell not measurable', c); continue
        a0, g0 = ra[0][0], rg[0][0]; pa, pg = (ra[NLINES - 1][0] - a0) / (NLINES - 1), (rg[NLINES - 1][0] - g0) / (NLINES - 1)
        e = acc.setdefault(c['fam'], {}); e.setdefault(c['lh'], []).append(dict(dy=(g0 - a0) / FS, pitch_ratio=pg / pa, w=c['w']))
    out = {}; report = {}
    for fam, byl in acc.items():
        dy = [[lh, float(np.mean([m['dy'] for m in ms]))] for lh, ms in sorted(byl.items())]
        ratio = float(np.mean([m['pitch_ratio'] for ms in byl.values() for m in ms])); nat = table.get(fam, {}).get('natural', 1.21)
        meas = nat * ratio; ent = dict(dy=dy, natural_measured=round(meas, 4))
        if abs(meas / nat - 1) > 0.01: ent['natural'] = round(meas, 4)
        out[fam] = ent; report[fam] = dict(natural_table=nat, pitch_ratio=round(ratio, 4), spread_dy_by_weight=max(abs(ms[0]['dy'] - ms[-1]['dy']) for ms in byl.values()) * FS)
    return dict(note='generated by d2s calibrate; dy is Google minus browser, fraction of font size', fonts=out), report


# ---- size/weight/tracking-specific calibration ---------------------------------------------------------------------------------
# The 60 px / weight-400 table above assumes dy scales linearly with font size and ignores tracking. Neither holds (display type at
# 220-400 px sits several px high in Google, and tracked text drifts sideways and narrows), so every (size, line-height, weight,
# letter-spacing) combination a deck uses gets its own measured cell: dy (vertical), dx (left edge) and dadv (advance per character).
def combos_from_slides(slides_json, fam='Inter'):
    """-> sorted unique (fs, lh, weight, letter-spacing px) over every text run's block, from extract's slides.json"""
    out = set()
    for s in json.load(open(slides_json)):
        for it in s['items']:
            t = it.get('text')
            if not t or t['fam'] != fam: continue
            for r in t['runs']:
                if r.get('br'): continue
                out.add((int(round(t['fs'])), round(t['lh'] or 0, 3), int(r['w']), round(r.get('ls') or 0, 1)))
    return sorted(out)

def _nchars(fs): return 8 if fs <= 60 else (4 if fs <= 130 else 2)

def make_size_deck(deck_json, fam, combos, outdir):
    src = json.load(open(deck_json))
    os.makedirs(outdir + '/slides', exist_ok=True); order = []; cells = []; slides = [[]]; x = y = 40; rowh = 0
    for fs, lh, w, ls in combos:                   # shelf-pack one 'HHH..' per combination
        n = _nchars(fs); cw = int(n * fs * 0.8) + 100; ch = int(fs * max(lh, 1.0)) + 50
        if x + cw > 1880: x = 40; y += rowh + 20; rowh = 0
        if y + ch > 1040: slides.append([]); x = y = 40; rowh = 0
        slides[-1].append((fs, lh, w, ls, n, x, y, cw, ch)); x += cw; rowh = max(rowh, ch)
    for si, group in enumerate(slides):
        sid = 'size%d' % si; order.append(sid); html = ['<section id="%s">' % sid]
        for fs, lh, w, ls, n, x, y, cw, ch in group:
            html.append('<div style="position:absolute;left:%dpx;top:%dpx;white-space:nowrap;font-family:\'%s\';font-weight:%d;font-size:%dpx;line-height:%s;letter-spacing:%spx;color:#000">%s</div>' % (x + 20, y, fam, w, fs, lh, ls, 'H' * n))
            cells.append(dict(slide=si + 1, fam=fam, w=w, lh=lh, fs=fs, ls=ls, n=n, box=[x - 4, y - 4, x + cw, y + ch]))
        html.append('</section>'); open('%s/slides/%s.html' % (outdir, sid), 'w').write('\n'.join(html))
    json.dump(dict(v=5, title='size calibration', order=order, faces={k: v for k, v in src['faces'].items() if v['family'] == fam}), open(outdir + '/deck.json', 'w'))
    open(outdir + '/deck.css', 'w').write('section{background:#fff;color:#000;padding:0;display:block}')
    json.dump(cells, open(outdir + '/cells.json', 'w'), indent=1); return cells

def _ink(I, box):
    x0, y0, x1, y1 = box; m = I[y0:y1, x0:x1].max(2) < 110
    if m.sum() < 12: return None
    ys = np.where(m.any(1))[0]; xs = np.where(m.any(0))[0]; return x0 + xs[0], y0 + ys[0], x0 + xs[-1], y0 + ys[-1]

